import 'dotenv/config';
import mongoose from 'mongoose';
import { connectDatabase } from '../config/database.js';
import { User } from '../models/User.js';
import { Post } from '../models/Post.js';
import { Comment } from '../models/Comment.js';

try {
    if (process.env.NODE_ENV === 'production') throw new Error('Seed script is disabled in production.');
    if (process.env.ALLOW_DESTRUCTIVE_SEED !== 'true') throw new Error('Set ALLOW_DESTRUCTIVE_SEED=true to confirm clearing the configured development database.');
    if (!process.env.SEED_USER_PASSWORD || process.env.SEED_USER_PASSWORD.length < 16) throw new Error('Set SEED_USER_PASSWORD to a unique password of at least 16 characters.');
    await connectDatabase();
    await Promise.all([Comment.deleteMany({}), Post.deleteMany({}), User.deleteMany({})]);
    const user = await User.create({ name: 'Sample Author', email: 'author@example.test', passwordHash: process.env.SEED_USER_PASSWORD, bio: 'A development-only sample author.' });
    const post = await Post.create({ title: 'Welcome to BlogSphere', excerpt: 'A sample post for local development.', content: 'This sample post is generated by the development seed script. Replace it with your own writing.', category: 'Technology', tags: ['welcome', 'development'], status: 'published', author: user._id });
    await Comment.create({ post: post._id, author: user._id, content: 'Sample comment: your BlogSphere backend is ready.' });
    console.log('Seeded local sample user, post, and comment.');
} catch (error) {
    console.error(`Seed failed: ${process.env.NODE_ENV === 'production' ? 'operation refused or database error' : error.message}`);
    process.exitCode = 1;
} finally {
    await mongoose.disconnect();
}